using Vortex.Core.Extensions.LogicExtensions.SerializationSystem;

namespace Vortex.Core.SaveSystem.Abstraction
{
    /// <summary>
    /// Модуль межсессионных данных пакета — блок, который переживает слоты сохранения, новые игры и перезапуски.
    /// Аналог <c>GameModel.IGameData</c> для глобального хранилища (<c>GlobalSaveController</c>).
    ///
    /// Реализации обязан быть доступен публичный конструктор без параметров: хранилище собирает модули
    /// рефлексией, и конструктор задаёт значения по умолчанию. Данные модуля — его свойства; модуль
    /// сериализуется целиком сериализатором Vortex, код сохранения ему не нужен.
    ///
    /// Смена формата между версиями — забота модуля: недостающие свойства берут значения по умолчанию,
    /// лишние игнорируются.
    /// </summary>
    [POCO]
    public interface IGlobalData
    {
        /// <summary>
        /// Стабильный ключ модуля в хранилище. От имени класса не зависит: переименование и перенос класса
        /// данные не ломают. Смена ключа после релиза — потеря данных модуля.
        /// </summary>
        string GetGlobalKey();
    }
}
