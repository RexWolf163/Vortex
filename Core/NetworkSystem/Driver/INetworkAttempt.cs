using System;

namespace Vortex.Core.NetworkSystem.Driver
{
    /// <summary>
    /// Одна попытка в транспорте: запустить, читать прогресс отправки и скачивания, узнать о готовности,
    /// получить результат, прервать, сохранить файл ответа, освободить ресурсы. Таймаут, отмену и наблюдение
    /// ведёт контроллер.
    /// </summary>
    /// <remarks>
    /// <para>Сбой транспорта — не исключение, а результат с категорией ошибки.</para>
    /// <para>
    /// Освобождает попытку всегда контроллер, на любом исходе. <see cref="IDisposable.Dispose"/> освобождает
    /// ресурсы транспорта и временные файлы; идущую попытку прерывает; повторный вызов безопасен.
    /// </para>
    /// </remarks>
    public interface INetworkAttempt : IDisposable
    {
        /// <summary>Запустить попытку. Вызывается один раз: повторный вызов — ошибка программиста.</summary>
        void Run();

        /// <summary>Прогресс отправки, 0…1. Транспорт без прогресса отправки — 0 до завершения, затем 1.</summary>
        float UploadProgress { get; }

        /// <summary>Прогресс скачивания, 0…1. Размер ответа неизвестен — 0 до завершения, затем 1.</summary>
        float DownloadProgress { get; }

        /// <summary>Попытка завершена: результат готов.</summary>
        bool IsDone { get; }

        /// <summary>
        /// Результат попытки. До завершения — <c>null</c>. От ресурсов транспорта не зависит: читается
        /// и после освобождения попытки.
        /// </summary>
        AttemptResult Result { get; }

        /// <summary>
        /// Прервать попытку. После прерывания контроллер результат не читает и сразу освобождает попытку.
        /// На завершённой попытке ничего не делает.
        /// </summary>
        void Abort();

        /// <summary>
        /// Сохранить файл ответа: перенести временный файл на путь приёмника
        /// (<see cref="PreparedAttempt.ResponseFilePath"/>). Файл, уже лежащий по этому пути, заменяется.
        /// Сохранять ли файл, решает контроллер: вызывает один раз, после завершения попытки и до её
        /// освобождения, только у попытки с файлом-приёмником. Без вызова временный файл удаляется
        /// при освобождении.
        /// </summary>
        /// <param name="error">Сообщение о сбое переноса. <c>null</c>, если файл сохранён.</param>
        /// <returns><c>true</c> — файл лежит по пути приёмника; <c>false</c> — перенести не удалось.</returns>
        bool SaveResponseFile(out string error);
    }
}
