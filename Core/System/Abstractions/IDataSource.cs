using System;

namespace Vortex.Core.System.Abstractions
{
    /// <summary>
    /// Контракт источника данных, отдающего ссылки на объекты-данные наружу
    /// (реактивные контейнеры, ссылочные модели, любые ссылочные типы).
    ///
    /// Событие <see cref="OnUpdateLink"/> сигнализирует, что выдаваемые через
    /// потребительский API (например, <c>IDataStorage.GetData&lt;T&gt;()</c>) ссылки
    /// были пересозданы или замещены — потребителю нужно перезапросить их и,
    /// если данные реактивные, переподписаться на их собственные события обновления.
    ///
    /// Событие НЕ сигнализирует:
    ///  • об изменении внутреннего состояния уже выданных объектов
    ///    (для реактивных данных — подписывайтесь на их <c>OnUpdate</c> напрямую;
    ///    для прочих ссылочных типов — наблюдайте через свои механизмы);
    ///  • о добавлении новых объектов без замены существующих
    ///    (ранее полученные ссылки остаются валидными).
    /// </summary>
    public interface IDataSource
    {
        public event Action OnUpdateLink;
    }
}