namespace Vortex.Unity.UI.VirtualCursorSystem
{
    /// <summary>
    /// Характер источника позиции курсора — по способу получения, не по устройству.
    /// Несколько устройств делят один вид; арбитраж и порог активности зависят от вида.
    /// </summary>
    public enum PointerSourceKind
    {
        /// <summary>Непрерывное аналоговое указание (мышь): позиция есть всегда, нужен порог активности.</summary>
        Analog,

        /// <summary>Абсолютная точка по касанию (тач/тачпад): позиция = точка контакта.</summary>
        Point,

        /// <summary>Направленный ввод (геймпад/клавиши): позиция интегрируется (скорость×dt, кламп к экрану).</summary>
        Direct,
    }
}
