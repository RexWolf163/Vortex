#if USING_VORTEX_SHOP
namespace Vortex.Sdk.ShopSystem.Model
{
    /// <summary>
    /// Состояние операции покупки, зафиксированное в журнале как тип события.
    /// Не рантайм-флаг: восстанавливается сворачиванием событий по purchaseGuid,
    /// поэтому переживает перезапуск (в пределах последней точки сохранения).
    /// </summary>
    public enum PurchaseState
    {
        /// <summary>Заказ заведён, предпроверки пройдены, оплата ещё не проводилась.</summary>
        Ordered,

        /// <summary>Оплата подтверждена.</summary>
        Paid,

        /// <summary>Оплачено, выдача ждёт подтверждения игроком. Автовыдачи не происходит.</summary>
        Ready,

        /// <summary>Выдача сорвалась, покупка удерживается открытой для повторной попытки.</summary>
        Pending,

        /// <summary>Товар выдан, сделка закрыта успешно. Терминальное.</summary>
        Delivered,

        /// <summary>Оплата возвращена после несостоявшейся выдачи. Терминальное.</summary>
        Refunded,

        /// <summary>Прерывание по проверкам. Не должно быть занесено в журнал.</summary>
        NotStarted,

        /// <summary>Оплата не прошла, ничего не списано. Терминальное.</summary>
        Cancelled,

        /// <summary>Ни выдать, ни вернуть невозможно — у товара нет логик. Терминальное.</summary>
        Failed
    }
}
#endif