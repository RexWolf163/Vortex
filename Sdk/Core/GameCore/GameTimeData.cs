namespace Vortex.Sdk.Core.GameCore
{
    /// <summary>
    /// Тайминги, привязанные к сейву. Живёт в теле сохранения (слот "GameSave"),
    /// в SaveSummary не выносится.
    ///
    /// Важно: у класса обязан оставаться публичный конструктор без параметров —
    /// ComplexModel.Init() собирает реализации IGameData рефлексией и берёт только
    /// типы с таким конструктором. Иначе модуль молча не попадёт в индекс.
    ///
    /// Атрибут [POCO] не нужен: он уже стоит на GameModel.IGameData, а проверка
    /// сериализатора учитывает интерфейсы. Свойства с internal-сеттером сериализуются.
    /// </summary>
    public class GameTimeData : GameModel.IGameData
    {
        /// <summary>
        /// Накопленные секунды прохождения — время в состоянии <see cref="GameStates.Play"/>.
        /// Физический смысл — «время конкретного прохождения»: при загрузке принимает
        /// значение слота, а не продолжает предыдущее.
        /// </summary>
        public long PlaySeconds { get; internal set; }

        /// <summary>
        /// Unix-секунды начала прохождения. Потребитель — аналитика.
        /// Для сейвов старого формата (поля нет) проставляется датой первой загрузки.
        /// </summary>
        public long SessionStartedAt { get; internal set; }

        /// <summary>
        /// Отпечаток суммарного времени приложения на момент сохранения.
        /// Только аналитика: при загрузке глобальный счётчик не переопределяет.
        /// </summary>
        public long AppSecondsSnapshot { get; internal set; }
    }
}
