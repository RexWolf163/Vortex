#if USING_VORTEX_ITEMS
using System;
using Sirenix.OdinInspector;
using Vortex.Unity.EditorTools.Attributes;

namespace Vortex.Sdk.ItemsSystem.Model
{
    /// <summary>
    /// База свойства предмета — тип хранения в полиморфном массиве пресета и в словаре модели.
    /// Тип запроса при этом другой: интерфейс назначения (см. <see cref="IItemProperty"/>).
    /// Разделение осознанное — полиморфное хранение требует класса, поиск по возможности — интерфейса.
    ///
    /// Наследник на уровне 4 делит свои поля на две категории:
    /// настроечные (приходят из пресета, помечаются <c>[NotPOCO]</c>, в сохранение не идут),
    /// игровое состояние (сохраняется, умолчание сериализатора именно такое).
    ///
    /// Умолчание сериализации — «сохраняется». Забытая пометка исключения на настроечном поле
    /// приведёт к тому, что значение уедет в сейв, перекроет настройку при загрузке и патч баланса
    /// перестанет доходить до старых предметов молча. Это главный риск пакета, см. README.
    ///
    /// Свойство, которое предполагается добавлять в рантайме, настроечных полей иметь не должно:
    /// у него нет пресета-источника, и при воссоздании из сохранения такие поля придут нулями.
    ///
    /// Реактивность: контроллер, изменивший значение свойства, зовёт <see cref="ItemModel.NotifyChanged"/>
    /// у владеющего предмета — так изменение доходит до инвентаря и его подписчиков без полинга.
    /// </summary>
    [Serializable, HideReferenceObjectPicker, ClassLabel("$Label")]
    public abstract class ItemProperty : IItemProperty
    {
        protected virtual string Label => GetType().Name;

        /// <summary>
        /// Сообщить, что значение свойства изменилось. Наследник зовёт это после мутации, передавая
        /// предмет-владельца (ссылку свойство не хранит — она замкнула бы цикл в сериализации, поэтому
        /// приходит параметром, как в <c>GetMass(owner)</c>). Сигнал доходит до инвентаря и его
        /// подписчиков без полинга.
        /// </summary>
        protected void NotifyChanged(ItemModel owner) => owner.NotifyChanged();
    }
}
#endif